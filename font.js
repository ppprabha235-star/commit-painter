// Turns text into a flat list of {col, row} cells lit up, laid out
// left-to-right with 1 blank column between letters. row/col are 0-based,
// 7 rows tall (matching a GitHub contribution week), as many cols wide
// as the text needs.
export function textToCells(text) {
  const cells = [];
  let colOffset = 0;

  for (const rawChar of text.toUpperCase()) {
    const glyph = GLYPHS[rawChar] || GLYPHS[" "];
    for (let row = 0; row < 7; row++) {
      for (let col = 0; col < 5; col++) {
        if (glyph[row][col] === "#") {
          cells.push({ col: colOffset + col, row });
        }
      }
    }
    colOffset += 6; // 5-wide glyph + 1 column of spacing
  }

  return { cells, width: Math.max(colOffset - 1, 0) };
}
